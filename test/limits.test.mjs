import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {openDatabase} from '../scripts/sqlite.mjs';
import {feedSignature} from '../src/refresh.mjs';
import {addJob,runRefresh,statement} from '../src/refresh.mjs';
import {HOSTS} from '../src/sources.mjs';
const migration=await fs.readFile(new URL('../migrations/0001_initial.sql',import.meta.url),'utf8');
test('a rate limit pauses all jobs using the same API key',async()=>{
  const db=openDatabase(':memory:');db.exec(migration);db.exec(`INSERT INTO metadata VALUES ('initialized','test fixture'),('feeds','${feedSignature()}')`);
  for(const id of ['a','b'])await addJob(db,`campaign:${id}`,'campaign',id,{committee:'C00314575',cycle:2026});
  let requests=0;const started=Date.now();
  await runRefresh({DB:db,FEC_API_KEY:'test',fetch:async()=>{requests++;return new Response('rate limited',{status:429,headers:{'Retry-After':'120'}});}},{steps:8});
  assert.equal(requests,1);
  const jobs=(await statement(db,"SELECT next_due FROM jobs WHERE kind='campaign'").all()).results;
  assert.ok(jobs.every(j=>j.next_due>=started+120000));db.close();
});
test('each source gets only its share of a run, and a job that has started fetching pages finishes first',async()=>{
  const db=openDatabase(':memory:');db.exec(migration);db.exec(`INSERT INTO metadata VALUES ('initialized','test fixture'),('feeds','${feedSignature()}')`);
  for(let i=0;i<10;i++)await addJob(db,`news-nyt:p${i}`,'news-nyt',`p${i}`,{name:`Person ${i}`});
  for(let i=0;i<3;i++)await addJob(db,`campaign:c${i}`,'campaign',`c${i}`,{committee:'C00314575',cycle:2026});
  const hosts=[];
  await runRefresh({DB:db,FEC_API_KEY:'f',NYT_API_KEY:'n',fetch:async u=>{hosts.push(new URL(String(u)).host);return new Response('{}',{status:500});}},{steps:40});
  assert.equal(hosts.filter(h=>h==='api.nytimes.com').length,HOSTS['api.nytimes.com'].perRun,'the New York Times gets at most its share');
  assert.equal(hosts.filter(h=>h==='api.open.fec.gov').length,3,'other sources still run in the same pass');
  await statement(db,"UPDATE jobs SET next_due=0,status='pending'").run();
  await statement(db,"UPDATE jobs SET cursor=?,run_id='r',started_at=? WHERE id='news-nyt:p9'",JSON.stringify({todo:[2025,2026],i:1,at:null}),new Date().toISOString()).run();
  const order=[];
  await runRefresh({DB:db,FEC_API_KEY:'f',NYT_API_KEY:'n',fetch:async u=>{order.push(String(u));return new Response('{}',{status:500});}},{steps:1});
  assert.equal(order.length,1);assert.equal(new URL(order[0]).host,'api.nytimes.com');
  assert.equal((await statement(db,"SELECT failures FROM jobs WHERE id='news-nyt:p9'").first()).failures>0,true,'the started job ran first');
  db.close();
});
